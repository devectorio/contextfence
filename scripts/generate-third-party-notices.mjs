#!/usr/bin/env node

import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'

const root = resolve(import.meta.dirname, '..')
const requireFromRoot = createRequire(import.meta.url)

const packages = [
  {
    name: '@fontsource-variable/manrope',
    attribution: 'Copyright 2019 The Manrope Project Authors (https://github.com/sharanda/manrope)',
  },
  {
    name: '@fontsource/dm-mono',
    attribution: 'Copyright 2020 The DM Mono Project Authors (https://www.github.com/googlefonts/dm-mono)',
  },
  { name: 'react' },
  { name: 'react-dom' },
  { name: 'scheduler', resolveFrom: 'react-dom' },
  { name: 'lucide-react' },
  { name: 'vite' },
  { name: 'yaml' },
]

function packageManifestPath(entry) {
  if (!entry.resolveFrom) return requireFromRoot.resolve(`${entry.name}/package.json`)
  const parentManifest = requireFromRoot.resolve(`${entry.resolveFrom}/package.json`)
  return createRequire(parentManifest).resolve(`${entry.name}/package.json`)
}

function repositoryUrl(manifest) {
  const repository = typeof manifest.repository === 'string'
    ? manifest.repository
    : manifest.repository?.url
  return repository ?? manifest.homepage ?? 'Not declared'
}

function licenseText(packageDirectory) {
  for (const filename of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'LICENCE.md']) {
    const path = join(packageDirectory, filename)
    if (existsSync(path)) return readFileSync(path, 'utf8').trim()
  }
  throw new Error(`No license text found in ${packageDirectory}`)
}

const sections = packages.map((entry) => {
  const manifestPath = packageManifestPath(entry)
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  const metadata = [
    `${manifest.name} ${manifest.version}`,
    `License: ${manifest.license ?? 'See text below'}`,
    `Source: ${repositoryUrl(manifest)}`,
    ...(entry.attribution ? [`Attribution: ${entry.attribution}`] : []),
  ].join('\n')
  return `${metadata}\n\n${licenseText(dirname(manifestPath))}`
})

const output = `CONTEXTFENCE THIRD-PARTY NOTICES

This distribution includes or may redistribute the packages and font software listed below. The following notices are provided for attribution and do not change the Apache-2.0 license of ContextFence itself.

This file is generated by scripts/generate-third-party-notices.mjs. Do not edit it by hand.

${sections.join('\n\n================================================================================\n\n')}
`

const destinations = [
  resolve(root, 'THIRD_PARTY_NOTICES.txt'),
  resolve(root, 'public/THIRD_PARTY_NOTICES.txt'),
]

if (process.argv.includes('--check')) {
  const stale = destinations.filter(
    (path) => !existsSync(path) || readFileSync(path, 'utf8') !== output,
  )
  if (stale.length > 0) {
    console.error(`Third-party notices are stale: ${stale.join(', ')}`)
    console.error('Run: node scripts/generate-third-party-notices.mjs')
    process.exit(1)
  }
  console.log('Third-party notices are current.')
  process.exit(0)
}

for (const destination of destinations) writeFileSync(destination, output)
console.log(`Wrote ${destinations.length} third-party notice files.`)
